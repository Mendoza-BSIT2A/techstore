-- The app never talks to this table directly. It calls the custom REST API in
-- supabase/functions/store-api/index.ts, which uses the service role. Row Level
-- Security is enabled with no policies, so the public anon key cannot read or
-- change data.

drop table if exists public.products;

create table public.products (
  id            bigint generated by default as identity primary key,
  name          varchar(120)  not null check (char_length(btrim(name)) between 2 and 120),
  category      varchar(20)   not null check (category in ('Laptop', 'Parts', 'Accessories')),
  brand         varchar(60)   not null default '',
  price         numeric(10,2) not null check (price between 0.01 and 1000000 and price = round(price, 2)),
  stock         integer       not null check (stock between 0 and 100000),
  description   text          not null default '' check (char_length(description) <= 2000),
  image_url     varchar(500)  check (image_url ~* '^https?://[^[:space:]]+$'),
  dummyjson_id  integer       check (dummyjson_id > 0),  -- id of the linked product on dummyjson.com
  created_at    timestamptz   not null default now(),
  updated_at    timestamptz   not null default now()
);

-- Product names are unique regardless of letter case ("Dell XPS 13" = "dell xps 13").
create unique index products_name_unique on public.products (lower(name));
create index products_category_idx on public.products (category);

-- Keep updated_at current on every UPDATE. The table has its own function so
-- the Dog Breed app's public.set_updated_at() is never replaced.
create or replace function public.products_set_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create trigger products_set_updated_at
  before update on public.products
  for each row execute function public.products_set_updated_at();

-- Only the Edge Function (service role) may access the table.
alter table public.products enable row level security;

-- Supabase grants this by default; repeated so the API keeps working even if
-- the project's default privileges were changed.
grant select, insert, update, delete on public.products to service_role;

